"""Generate idiomatic Swift models and wrappers over the shared Rust execution core."""
import re
from sdk_contracts import ROOT, RESOURCE_NAMES, read_contracts, resource_models, model_definitions, operation_models


def outputs():
    routes, _ = read_contracts("swift")
    models = {**model_definitions("swift"), **operation_models("swift")}
    models.update(resource_models(routes))
    # The mutable, synchronized checkpoint has a hand-written lifecycle implementation.
    models.pop("ListingImageUploadCheckpoint", None)
    lines = ['// Generated by scripts/generate_sdks.py. Do not edit.', 'import Foundation', '']
    emitted = set()

    def swift_type(value, hint):
        if '$ref' in value:
            return value['$ref'].rsplit('/', 1)[-1]
        kind = value.get('type')
        if kind == 'array':
            return '[' + swift_type(value['items'], hint + 'Item') + ']'
        if kind == 'object':
            if not value.get('properties'):
                return '[String: JSONValue]'
            emit(hint, value)
            return hint
        return {'string': 'String', 'boolean': 'Bool', 'integer': 'Int', 'number': 'Double'}.get(kind, 'JSONValue')

    def emit(name, schema):
        if name in emitted:
            return
        emitted.add(name)
        if name == 'ListingImagePlacementType':
            lines.extend(['public enum ListingImagePlacementType: String, Codable, Sendable {',
                          '    case productPageHeaderAsset = "PRODUCT_PAGE_HEADER_ASSET"',
                          '    case appStoreSearchResultsAsset = "APP_STORE_SEARCH_RESULTS_ASSET"', '}', ''])
            return
        if schema.get('type') != 'object':
            # Apple can add read enum values without an SDK release.
            lines.extend([f'public typealias {name} = {swift_type(schema, name)}', ''])
            return
        fields = []
        for field, value in schema['properties'].items():
            ty = swift_type(value, name + field[0].upper() + field[1:])
            optional = field not in schema.get('required', []) or value.get('nullable')
            fields.append((field, ty + ('?' if optional else ''), optional))
        lines.append(f'public struct {name}: Codable, Sendable, Equatable {{')
        lines.extend(f'    public let {field}: {ty}' for field, ty, _ in fields)
        args = ', '.join(f'{field}: {ty}' + (' = nil' if optional else '') for field, ty, optional in fields)
        lines.append(f'    public init({args}) {{')
        lines.extend(f'        self.{field} = {field}' for field, _, _ in fields)
        lines.extend(['    }', '}', ''])

    for name, schema in models.items():
        emit(name, schema)
    lines.append('extension Client {')
    for route in routes:
        params = re.findall(r'\{(\w+)\}', route['route'])
        result = RESOURCE_NAMES[route['type']]
        if route['collection']:
            result = f'Page<{result}>'
        args = ''.join(f'{p}: String, ' for p in params)
        path = route['route']
        for p in params:
            path = path.replace('{' + p + '}', '\\(' + p + ')')
        lines.extend([f'    /// Read `{route["route"]}` directly from Apple.',
                      f'    public func {route["handler"]}({args}query: Query = [:]) async throws -> {result} {{'])
        # Validate before interpolation so slashes cannot change route selection.
        for p in params:
            lines.append(f'        try validateSegment({p}, locale: {str(p == "locale").lower()})')
        lines.extend([f'        return try await get("{path}", query: query, as: {result}.self)', '    }', ''])
    lines.extend(['}', ''])
    base = ROOT / 'sdks/swift'
    return {
        base / 'Sources/Parsequerade/Generated.swift': '\n'.join(lines),
        base / 'LICENSE': (ROOT / 'LICENSE').read_text(),
    }
