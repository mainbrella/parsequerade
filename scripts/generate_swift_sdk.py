"""Generate Swift Codable models, resource methods and bundled runtime contracts."""
import json
import re
from sdk_contracts import ROOT, RESOURCE_NAMES, read_contracts, resource_models, runtime_contracts


def outputs():
    routes, _ = read_contracts()
    lines = ['// Generated by scripts/generate_sdks.py. Do not edit.', 'import Foundation', '']
    for name, schema in resource_models(routes):
        lines += [f'public struct {name}: Codable, Sendable, Equatable {{']
        for field, value in schema['properties'].items():
            ty = {'string': 'String', 'boolean': 'Bool'}[value['type']]
            if field not in schema['required']:
                ty += '?'
            lines += [f'    public let {field}: {ty}']
        lines += ['}', '']
    lines += ['extension Client {']
    for route in routes:
        params = re.findall(r'\{(\w+)\}', route['route'])
        result = RESOURCE_NAMES[route['type']]
        if route['collection']:
            result = f'Page<{result}>'
        args = ''.join(f'{p}: String, ' for p in params)
        path = route['route']
        for p in params:
            path = path.replace('{' + p + '}', '\\(' + p + ')')
        lines += [f'    /// Read `{route["route"]}` directly from Apple.',
                  f'    public func {route["handler"]}({args}query: Query = [:]) async throws -> {result} {{']
        for p in params:
            lines += [f'        try validateSegment({p}, locale: {str(p == "locale").lower()})']
        lines += [f'        return try await get("{path}", query: query, as: {result}.self)', '    }', '']
    lines += ['}', '']
    base = ROOT / 'sdks/swift'
    return {
        base / 'Sources/Parsequerade/Generated.swift': '\n'.join(lines),
        base / 'Sources/Parsequerade/Resources/contracts.json': json.dumps(runtime_contracts(), indent=2) + '\n',
        base / 'LICENSE': (ROOT / 'LICENSE').read_text(),
    }
