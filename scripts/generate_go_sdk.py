"""Generate Go's public models, queries, methods and embedded contracts (no Go toolchain needed)."""
import json
import re

from sdk_contracts import ROOT, RESOURCE_NAMES, read_contracts, resource_models, runtime_contracts


def exported(value):
    words = re.findall(r"[A-Z]?[a-z]+|[A-Z]+(?=[A-Z]|$)|[0-9]+", value)
    initialisms = {"id": "ID", "url": "URL", "sku": "SKU"}
    return "".join(initialisms.get(w.lower(), w[0].upper() + w[1:]) for w in words)


def argument(value):
    return value[:-2] + "ID" if value.endswith("Id") else value


def struct(name, fields):
    width = max(len(f[0]) for f in fields)
    type_width = max(len(f[1]) for f in fields)
    return [f"type {name} struct {{", *[
        f'\t{field:<{width}} {kind:<{type_width}} {tag}'.rstrip()
        for field, kind, tag in fields
    ], "}", ""]


def model(name, properties, required=()):
    fields = []
    for field, schema in properties.items():
        kind = {"string": "string", "boolean": "bool"}[schema["type"]]
        if field not in required:
            kind = f"Optional[{kind}]"
        fields.append((exported(field), kind, f'`json:"{field}"`'))
    lines = struct(name, fields)
    lines += [f"func (v {name}) MarshalJSON() ([]byte, error) {{", "\tm := map[string]any{}"]
    for field in properties:
        if field in required:
            lines += [f'\tm["{field}"] = v.{exported(field)}']
        else:
            lines += [f'\taddField(m, "{field}", v.{exported(field)})']
    return lines + ["\treturn json.Marshal(m)", "}", ""]


def outputs():
    routes, write = read_contracts("go")
    lines = ["// Code generated by scripts/generate_sdks.py. DO NOT EDIT.", "package parsequerade", "",
             'import (', '\t"context"', '\t"encoding/json"', '\t"strconv"', '\t"strings"', ')', '']
    for name, schema in resource_models(routes):
        lines += model(name, schema["properties"], schema["required"])
    lines += model("AgeRatingUpdate", write["attributes"])
    for route in routes:
        name = exported(route["handler"]) + "Query"
        fields = [(exported(p["name"]), {"array": "[]string", "string": "string", "integer": "int", "boolean": "*bool"}[p["schema"]["type"]], "") for p in route["parameters"]]
        lines += struct(name, fields)
        lines += [f"func (q *{name}) Values() Query {{", "\tv := Query{}", "\tif q == nil {", "\t\treturn v", "\t}"]
        for p in route["parameters"]:
            field = "q." + exported(p["name"])
            kind = p["schema"]["type"]
            cond, expression = {
                "array": (f"{field} != nil", f'strings.Join({field}, ",")'),
                "string": (f'{field} != ""', field),
                "integer": (f"{field} != 0", f"strconv.Itoa({field})"),
                "boolean": (f"{field} != nil", f"strconv.FormatBool(*{field})"),
            }[kind]
            lines += [f"\tif {cond} {{", f'\t\tv.Set("{p["name"]}", {expression})', "\t}"]
        lines += ["\treturn v", "}", ""]
        params = re.findall(r"\{(\w+)\}", route["route"])
        result = RESOURCE_NAMES[route["type"]]
        if route["collection"]:
            result = f"Page[{result}]"
        args = "".join(f", {argument(p)} string" for p in params)
        lines += [f'// {exported(route["handler"])} reads {route["route"]} directly from Apple.',
                  f'func (c *Client) {exported(route["handler"])}(ctx context.Context{args}, query *{name}) ({result}, error) {{']
        for p in params:
            lines += [f'\tif err := validateSegment({argument(p)}, {str(p == "locale").lower()}); err != nil {{', f'\t\treturn {result}{{}}, err', '\t}']
        path = re.sub(r"\{(\w+)\}", lambda m: '"+' + argument(m[1]) + '+"', route["route"])
        # Avoid a trailing empty string after the last path parameter.
        expression = ('"' + path + '"').removesuffix('+""')
        lines += [f'\treturn readTyped[{result}](c, ctx, {expression}, query.Values())', "}", ""]
    base = ROOT / "sdks/go"
    return {
        base / "generated.go": "\n".join(lines),
        base / "contracts.json": json.dumps(runtime_contracts("go"), indent=2) + "\n",
        base / "LICENSE": (ROOT / "LICENSE").read_text(),
    }
