"""Generate Go's typed wrappers around the shared Rust execution core."""
import json
import re

from sdk_contracts import (
    ROOT, RESOURCE_NAMES, model_definitions, operation_models, read_contracts,
    resource_models, runtime_contracts,
)


def exported(value):
    words = re.findall(r"[A-Z]?[a-z]+|[A-Z]+(?=[A-Z]|$)|[0-9]+", value)
    initialisms = {"id": "ID", "url": "URL", "sku": "SKU", "http": "HTTP"}
    return "".join(initialisms.get(w.lower(), w[0].upper() + w[1:]) for w in words)


def argument(value):
    return value[:-2] + "ID" if value.endswith("Id") else value


def struct(name, fields):
    width = max((len(f[0]) for f in fields), default=0)
    type_width = max((len(f[1]) for f in fields), default=0)
    return [f"type {name} struct {{", *[
        f'\t{field:<{width}} {kind:<{type_width}} {tag}'.rstrip() for field, kind, tag in fields
    ], "}", ""]


def go_type(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    kind = schema.get("type")
    if kind == "array":
        return "[]" + go_type(schema["items"])
    return {"string": "string", "boolean": "bool", "integer": "int64", "number": "float64", "object": "map[string]any"}.get(kind, "any")


def model(name, properties, required=(), preserve_extra=False):
    fields = []
    for field, schema in properties.items():
        kind = go_type(schema)
        if field not in required:
            kind = f"Optional[{kind}]"
        fields.append((exported(field), kind, f'`json:"{field}"`'))
    if preserve_extra:
        fields.append(("Extra", "map[string]json.RawMessage", '`json:"-"`'))
    lines = struct(name, fields)
    lines += [f"func (v {name}) MarshalJSON() ([]byte, error) {{", "\tm := map[string]any{}"]
    if preserve_extra:
        lines += ['\tfor name, value := range v.Extra {', '\t\tm[name] = value', '\t}']
    for field in properties:
        if field in required:
            lines += [f'\tm["{field}"] = v.{exported(field)}']
        else:
            lines += [f'\tdelete(m, "{field}")', f'\taddField(m, "{field}", v.{exported(field)})']
    lines += ["\treturn json.Marshal(m)", "}", ""]
    if preserve_extra:
        lines += [f"func (v *{name}) UnmarshalJSON(data []byte) error {{", f"\ttype plain {name}", '\tvar decoded plain', '\tif err := json.Unmarshal(data, &decoded); err != nil {', '\t\treturn err', '\t}', '\tvar extra map[string]json.RawMessage', '\tif err := json.Unmarshal(data, &extra); err != nil {', '\t\treturn err', '\t}']
        lines += [f'\tdelete(extra, "{field}")' for field in properties]
        lines += [f'\t*v = {name}(decoded)', '\tif len(extra) != 0 {', '\t\tv.Extra = extra', '\t}', '\treturn nil', '}', '']
    return lines


def outputs():
    routes, write = read_contracts("go")
    lines = ["// Code generated by scripts/generate_sdks.py. DO NOT EDIT.", "package parsequerade", "",
             'import (', '\t"context"', '\t"encoding/json"', '\t"strconv"', '\t"strings"', ')', '']
    for name, schema in {**model_definitions("go"), **operation_models("go")}.items():
        if schema.get("type") == "object":
            lines += model(name, schema.get("properties", {}), schema.get("required", ()), name in model_definitions("go"))
        else:
            # Read enums stay open so future Apple values remain representable.
            lines += [f'type {name} = {go_type(schema)}', '']
    for name, schema in resource_models(routes):
        lines += model(name, schema["properties"], schema["required"])
    lines += model("AgeRatingUpdate", write["attributes"])
    for route in routes:
        name = exported(route["handler"]) + "Query"
        fields = [(exported(p["name"]), {"array": "[]string", "string": "string", "integer": "int", "boolean": "*bool"}[p["schema"]["type"]], "") for p in route["parameters"]]
        lines += struct(name, fields)
        lines += [f"func (q *{name}) Values() Query {{", "\tv := Query{}", "\tif q == nil {", "\t\treturn v", "\t}"]
        for p in route["parameters"]:
            field = "q." + exported(p["name"])
            cond, expression = {
                "array": (f"{field} != nil", f'strings.Join({field}, ",")'),
                "string": (f'{field} != ""', field),
                "integer": (f"{field} != 0", f"strconv.Itoa({field})"),
                "boolean": (f"{field} != nil", f"strconv.FormatBool(*{field})"),
            }[p["schema"]["type"]]
            lines += [f"\tif {cond} {{", f'\t\tv.Set("{p["name"]}", {expression})', "\t}"]
        lines += ["\treturn v", "}", ""]
        params = re.findall(r"\{(\w+)\}", route["route"])
        result = RESOURCE_NAMES[route["type"]]
        if route["collection"]:
            result = f"Page[{result}]"
        args = "".join(f", {argument(p)} string" for p in params)
        lines += [f'// {exported(route["handler"])} reads {route["route"]} using the shared Rust core.',
                  f'func (c *Client) {exported(route["handler"])}(ctx context.Context{args}, query *{name}) ({result}, error) {{']
        for p in params:
            lines += [f'\tif err := validateSegment({argument(p)}, {str(p == "locale").lower()}); err != nil {{', f'\t\treturn {result}{{}}, err', '\t}']
        path = re.sub(r"\{(\w+)\}", lambda m: '"+' + argument(m[1]) + '+"', route["route"])
        expression = ('"' + path + '"').removesuffix('+""')
        lines += [f'\treturn readTyped[{result}](c, ctx, {expression}, query.Values())', "}", ""]
    base = ROOT / "sdks/go"
    return {
        base / "generated.go": "\n".join(lines),
        base / "contracts.json": json.dumps(runtime_contracts("go"), indent=2) + "\n",
        base / "LICENSE": (ROOT / "LICENSE").read_text(),
    }
