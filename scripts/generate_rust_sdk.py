"""Generate the Rust SDK's contracts and response types from the facade contracts."""

import argparse
import json
import re
from sdk_contracts import CATALOG, ROOT, RESOURCE_NAMES, model_definitions, operation_models, read_contracts, resource_models, runtime_contracts

SDK = ROOT / "sdks/rust/src"
MODELS = model_definitions("rust")


def snake(value):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", value).lower()


def rust_type(schema, *, named_types=()):
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return name if name in named_types or MODELS[name]["type"] == "object" else rust_type(MODELS[name])
    if schema["type"] == "array":
        return f'Vec<{rust_type(schema["items"])}>'
    return {"object": "serde_json::Value", "string": "String", "boolean": "bool", "integer": "i64", "number": "f64"}[schema["type"]]


def upload_models():
    operation = CATALOG["operations"]["uploadListingImage"]
    models = operation_models("rust")
    source = ["// Generated by scripts/generate_rust_sdk.py. Do not edit.", ""]
    for key in ("request", "checkpoint", "result"):
        name = operation[key]
        schema = models[name]
        checkpoint = key == "checkpoint"
        derives = "Debug, Clone, " + ("Default, " if checkpoint else "") + "PartialEq, Eq, Serialize, Deserialize"
        source += [f"#[derive({derives})]", '#[serde(rename_all = "camelCase")]', f"pub struct {name} {{"]
        for field, value in schema["properties"].items():
            ty = rust_type(value, named_types={"ListingImagePlacementType"})
            if field not in schema.get("required", []):
                source += ['    #[serde(default, skip_serializing_if = "Option::is_none")]']
                ty = f"Option<{ty}>"
            visibility = "" if checkpoint else "pub "
            source += [f"    {visibility}{snake(field)}: {ty},"]
        source += ["}", ""]
    return "\n".join(source)


def outputs():
    routes, _ = read_contracts("rust")
    contracts = runtime_contracts("rust")
    source = [
        "// Generated by scripts/generate_rust_sdk.py. Do not edit.",
        "use crate::{Client, Page, Query, Result};",
        "use serde::{Deserialize, Serialize};",
        "",
    ]
    models = list(resource_models(read_contracts()[0]))
    models += [(name, schema) for name, schema in MODELS.items() if schema["type"] == "object"]
    models += list(resource_models(routes))
    seen_models = set()
    for name, schema in models:
        if name in seen_models:
            continue
        seen_models.add(name)
        source += ["#[rustfmt::skip]", "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]", '#[serde(rename_all = "camelCase")]', f'pub struct {name} {{']
        for field, value in schema["properties"].items():
            ty = rust_type(value)
            if field not in schema.get("required", []):
                source += ['    #[serde(default, skip_serializing_if = "Option::is_none")]']
                ty = f"Option<{ty}>"
            source += [f"    pub {snake(field)}: {ty},"]
        source += ["}", ""]
    source += ["#[rustfmt::skip]", "impl Client {"]
    for route in routes:
        params = re.findall(r"\{(\w+)\}", route["route"])
        ty = RESOURCE_NAMES[route["type"]]
        if route["collection"]:
            ty = f"Page<{ty}>"
        args = "".join(f", {snake(p)}: &str" for p in params)
        path = route["route"]
        for p in params:
            path = path.replace("{" + p + "}", "{" + snake(p) + "}")
        source += [
            f'    /// Read `{route["route"]}` directly from Apple.',
            f'    pub async fn {snake(route["handler"])}(&self{args}, query: &Query) -> Result<{ty}> {{',
        ]
        for p in params:
            validator = "crate::contract::validate_locale" if p == "locale" else "crate::contract::validate_id"
            source += [f"        {validator}({snake(p)})?;"]
        expression = f'&format!("{path}")' if params else f'"{path}"'
        source += [f"        self.get({expression}, query).await", "    }", ""]
    source += ["}", ""]
    return {
        SDK / "contracts.json": json.dumps(contracts, indent=2) + "\n",
        SDK / "generated.rs": "\n".join(source),
        SDK / "upload_models.rs": upload_models(),
        ROOT / "sdks/rust/LICENSE": (ROOT / "LICENSE").read_text(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"{path.relative_to(ROOT)} is stale; run python3 scripts/generate_rust_sdk.py")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
