"""Generate the Rust SDK's contracts and response types from the facade contracts."""

import argparse
import json
import re
from sdk_contracts import ROOT, RESOURCE_NAMES, read_contracts, resource_models, runtime_contracts

SDK = ROOT / "sdks/rust/src"
MEDIA = json.loads((ROOT / "api/rust-media-read-contracts.json").read_text())
NAMES = {**RESOURCE_NAMES, "appScreenshotSets": "ScreenshotSet", "appScreenshots": "Screenshot",
         "appPreviewSets": "PreviewSet", "appPreviews": "Preview"}


def snake(value):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", value).lower()


def resolved(value):
    if isinstance(value, list):
        return [resolved(item) for item in value]
    if not isinstance(value, dict):
        return value
    if "$ref" in value:
        return resolved(MEDIA["models"][value["$ref"].rsplit("/", 1)[-1]])
    return {key: resolved(item) for key, item in value.items()}


def rust_type(schema):
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return name if MEDIA["models"][name]["type"] == "object" else rust_type(MEDIA["models"][name])
    if schema["type"] == "array":
        return f'Vec<{rust_type(schema["items"])}>'
    return {"string": "String", "boolean": "bool", "integer": "i64", "number": "f64"}[schema["type"]]


def outputs():
    core_routes, _ = read_contracts()
    routes = core_routes + MEDIA["routes"]
    contracts = runtime_contracts()
    keys = ("handler", "route", "type", "collection", "attributes", "relationships", "parameters")
    contracts["routes"] += [{key: resolved(route[key]) for key in keys} for route in MEDIA["routes"]]
    source = [
        "// Generated by scripts/generate_rust_sdk.py. Do not edit.",
        "use crate::{Client, Page, Query, Result};",
        "use serde::{Deserialize, Serialize};",
        "",
    ]
    models = list(resource_models(core_routes))
    models += [(name, schema) for name, schema in MEDIA["models"].items() if schema["type"] == "object"]
    models += [(NAMES[route["type"]], route["responseSchema"]["properties"]["items"]["items"]) for route in MEDIA["routes"]]
    for name, schema in models:
        source += ["#[rustfmt::skip]", "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]", '#[serde(rename_all = "camelCase")]', f'pub struct {name} {{']
        for field, value in schema["properties"].items():
            ty = rust_type(value)
            if field not in schema.get("required", []):
                source += ['    #[serde(default, skip_serializing_if = "Option::is_none")]']
                ty = f"Option<{ty}>"
            source += [f"    pub {snake(field)}: {ty},"]
        source += ["}", ""]
    source += ["#[rustfmt::skip]", "impl Client {"]
    for route in routes:
        params = re.findall(r"\{(\w+)\}", route["route"])
        ty = NAMES[route["type"]]
        if route["collection"]:
            ty = f"Page<{ty}>"
        args = "".join(f", {snake(p)}: &str" for p in params)
        path = route["route"]
        for p in params:
            path = path.replace("{" + p + "}", "{" + snake(p) + "}")
        source += [
            f'    /// Read `{route["route"]}` directly from Apple.',
            f'    pub async fn {snake(route["handler"])}(&self{args}, query: &Query) -> Result<{ty}> {{',
        ]
        for p in params:
            validator = "crate::contract::validate_locale" if p == "locale" else "crate::contract::validate_id"
            source += [f"        {validator}({snake(p)})?;"]
        expression = f'&format!("{path}")' if params else f'"{path}"'
        source += [f"        self.get({expression}, query).await", "    }", ""]
    source += ["}", ""]
    return {
        SDK / "contracts.json": json.dumps(contracts, indent=2) + "\n",
        SDK / "generated.rs": "\n".join(source),
        ROOT / "sdks/rust/LICENSE": (ROOT / "LICENSE").read_text(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"{path.relative_to(ROOT)} is stale; run python3 scripts/generate_rust_sdk.py")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
