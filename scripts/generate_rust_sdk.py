"""Generate the Rust SDK's contracts and response types from the facade contracts."""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SDK = ROOT / "sdks/rust/src"


def snake(value):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", value).lower()


def outputs():
    manifest = json.loads((ROOT / "api/read-contracts.json").read_text())
    write = json.loads((ROOT / "api/age-rating-write-contract.json").read_text())
    routes = manifest["routes"]
    contracts = {
        "routes": [
            {key: r[key] for key in ("handler", "route", "type", "collection", "attributes", "relationships", "parameters")}
            for r in routes
        ],
        "ageRatingWrite": write["attributes"],
    }
    names = {
        "apps": "App", "appInfos": "AppInfo", "appInfoLocalizations": "AppInfoLocalization",
        "ageRatingDeclarations": "AgeRating", "appStoreVersions": "Version",
        "appStoreVersionLocalizations": "VersionLocalization", "appStoreReviewDetails": "ReviewContact",
    }
    source = [
        "// Generated by scripts/generate_rust_sdk.py. Do not edit.",
        "use crate::{Client, Page, Query, Result};",
        "use serde::{Deserialize, Serialize};",
        "",
    ]
    seen = set()
    for route in routes:
        if route["type"] in seen:
            continue
        seen.add(route["type"])
        schema = route["responseSchema"]
        if route["collection"]:
            schema = schema["properties"]["items"]["items"]
        source += ["#[rustfmt::skip]", "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]", '#[serde(rename_all = "camelCase")]', f'pub struct {names[route["type"]]} {{']
        for field, value in schema["properties"].items():
            ty = {"string": "String", "boolean": "bool"}[value["type"]]
            if field not in schema["required"]:
                source += ['    #[serde(default, skip_serializing_if = "Option::is_none")]']
                ty = f"Option<{ty}>"
            source += [f"    pub {snake(field)}: {ty},"]
        source += ["}", ""]
    source += ["#[rustfmt::skip]", "impl Client {"]
    for route in routes:
        params = re.findall(r"\{(\w+)\}", route["route"])
        ty = names[route["type"]]
        if route["collection"]:
            ty = f"Page<{ty}>"
        args = "".join(f", {snake(p)}: &str" for p in params)
        path = route["route"]
        for p in params:
            path = path.replace("{" + p + "}", "{" + snake(p) + "}")
        source += [
            f'    /// Read `{route["route"]}` directly from Apple.',
            f'    pub async fn {snake(route["handler"])}(&self{args}, query: &Query) -> Result<{ty}> {{',
        ]
        for p in params:
            validator = "crate::contract::validate_locale" if p == "locale" else "crate::contract::validate_id"
            source += [f"        {validator}({snake(p)})?;"]
        expression = f'&format!("{path}")' if params else f'"{path}"'
        source += [f"        self.get({expression}, query).await", "    }", ""]
    source += ["}", ""]
    return {
        SDK / "contracts.json": json.dumps(contracts, indent=2) + "\n",
        SDK / "generated.rs": "\n".join(source),
        ROOT / "sdks/rust/LICENSE": (ROOT / "LICENSE").read_text(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"{path.relative_to(ROOT)} is stale; run python3 scripts/generate_rust_sdk.py")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
