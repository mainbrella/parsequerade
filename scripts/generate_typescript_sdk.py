"""Generate TypeScript models, queries and thin methods from the facade contracts."""

import json
import re

from sdk_contracts import CATALOG, ROOT, RESOURCE_NAMES, model_definitions, operation_models, read_contracts, resource_models


def ts_type(schema, models, *, response=False, selection=False, optional=False):
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        target = models[name]
        result = name if target["type"] == "object" or not response else ts_type(target, models, response=True)
    elif "enum" in schema and not response:
        result = " | ".join(json.dumps(v) for v in schema["enum"])
    elif schema["type"] == "array":
        item = ts_type(schema["items"], models, response=response)
        result = f"Selection<{item}>" if selection else f"Array<{item}>"
    elif schema["type"] == "object":
        fields = []
        for name, value in schema.get("properties", {}).items():
            required = name in schema.get("required", [])
            fields.append(f"{name}{'' if required else '?'}: {ts_type(value, models, response=response, optional=not required)};")
        result = "{ " + " ".join(fields) + " }"
    else:
        result = {"string": "string", "boolean": "boolean", "integer": "number", "number": "number"}[schema["type"]]
    return result + (" | null" if schema.get("nullable") or response and optional else "")


def outputs():
    routes, write = read_contracts("typescript")
    reads = {**model_definitions("typescript"), **dict(resource_models(routes))}
    operations = operation_models("typescript")
    models = {**reads, **operations}
    lines = [
        "// Generated by scripts/generate_sdks.py. Do not edit.",
        "export type Selection<T extends string> = T | readonly T[];",
        "export type QueryValue = string | number | boolean | readonly string[];",
        "export type Query = Readonly<Record<string, QueryValue | undefined>> | URLSearchParams;",
        "export interface Page<T> { items: T[]; nextCursor: string | null; }",
        "",
    ]
    for name, schema in {**reads, **operations}.items():
        response = name in reads
        if schema["type"] != "object":
            lines += [f"export type {name} = {ts_type(schema, models)};", ""]
            continue
        lines += [f"export interface {name} {{"]
        for field, value in schema["properties"].items():
            optional = "" if field in schema.get("required", []) else "?"
            lines += [f"  {field}{optional}: {ts_type(value, models, response=response, optional=bool(optional))};"]
        lines += ["}", ""]
    lines += ["export interface AgeRatingUpdate {"]
    for field, schema in write["attributes"].items():
        lines += [f"  {field}?: {ts_type(schema, models)};"]
    lines += ["}", ""]
    for handler, attributes in CATALOG["metadataUpdates"].items():
        name = handler[0].upper() + handler[1:] + "Update"
        lines += [f"export interface {name} {{"]
        lines += [f"  {field}?: {ts_type(schema, models)};" for field, schema in attributes.items()]
        lines += ["}", ""]
    for route in routes:
        query_name = route["handler"][0].upper() + route["handler"][1:] + "Query"
        lines += [f"export type {query_name} = {{"]
        for parameter in route["parameters"]:
            lines += [f"  {parameter['name']}?: {ts_type(parameter['schema'], models, selection=True)};"]
        lines += ["};", ""]
    lines += [
        "/** Typed resource methods; all operation behavior lives in the shared Rust core. */",
        "export abstract class ResourceClient {",
        "  protected abstract getResource<T>(path: string, params: Record<string, string>, query: Query): Promise<T>;",
        "",
    ]
    for route in routes:
        params = re.findall(r"\{(\w+)\}", route["route"])
        result = RESOURCE_NAMES[route["type"]]
        if route["collection"]:
            result = f"Page<{result}>"
        query_name = route["handler"][0].upper() + route["handler"][1:] + "Query"
        args = "".join(f"{p}: string, " for p in params)
        values = "{ " + ", ".join(params) + " }" if params else "{}"
        lines += [
            f'  /** Read `{route["route"]}` directly from Apple. */',
            f'  {route["handler"]}({args}query: {query_name} | URLSearchParams = {{}}): Promise<{result}> {{',
            f'    return this.getResource("{route["route"]}", {values}, query);',
            "  }", "",
        ]
    lines += ["}", ""]
    return {
        ROOT / "sdks/typescript/src/generated.ts": "\n".join(lines),
        ROOT / "sdks/typescript/LICENSE": (ROOT / "LICENSE").read_text(),
    }
