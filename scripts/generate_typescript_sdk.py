"""Generate TypeScript models, queries and thin methods from the facade contracts."""

import json
import re

from sdk_contracts import ROOT, RESOURCE_NAMES, read_contracts, resource_models


def ts_type(schema):
    if "enum" in schema:
        result = " | ".join(json.dumps(v) for v in schema["enum"])
    elif schema["type"] == "array":
        result = f"Selection<{ts_type(schema['items'])}>"
    else:
        result = {"string": "string", "boolean": "boolean", "integer": "number"}[schema["type"]]
    return result + (" | null" if schema.get("nullable") else "")


def outputs():
    routes, write = read_contracts()
    lines = [
        "// Generated by scripts/generate_sdks.py. Do not edit.",
        "export type Selection<T extends string> = T | readonly T[];",
        "export type QueryValue = string | number | boolean | readonly string[];",
        "export type Query = Readonly<Record<string, QueryValue | undefined>> | URLSearchParams;",
        "export interface Page<T> { items: T[]; nextCursor: string | null; }",
        "",
    ]
    for name, schema in resource_models(routes):
        lines += [f"export interface {name} {{"]
        for field, value in schema["properties"].items():
            optional = "" if field in schema["required"] else "?"
            lines += [f"  {field}{optional}: {ts_type(value)};"]
        lines += ["}", ""]
    lines += ["export interface AgeRatingUpdate {"]
    for field, schema in write["attributes"].items():
        lines += [f"  {field}?: {ts_type(schema)};"]
    lines += ["}", ""]
    for route in routes:
        query_name = route["handler"][0].upper() + route["handler"][1:] + "Query"
        lines += [f"export type {query_name} = {{"]
        for parameter in route["parameters"]:
            lines += [f"  {parameter['name']}?: {ts_type(parameter['schema'])};"]
        lines += ["};", ""]
    lines += [
        "/** Typed resource methods; all behavior lives in the shared facade runtime. */",
        "export abstract class ResourceClient {",
        "  protected abstract getResource<T>(path: string, params: Record<string, string>, query: Query): Promise<T>;",
        "",
    ]
    for route in routes:
        params = re.findall(r"\{(\w+)\}", route["route"])
        result = RESOURCE_NAMES[route["type"]]
        if route["collection"]:
            result = f"Page<{result}>"
        query_name = route["handler"][0].upper() + route["handler"][1:] + "Query"
        args = "".join(f"{p}: string, " for p in params)
        values = "{ " + ", ".join(params) + " }" if params else "{}"
        lines += [
            f'  /** Read `{route["route"]}` directly from Apple. */',
            f'  {route["handler"]}({args}query: {query_name} | URLSearchParams = {{}}): Promise<{result}> {{',
            f'    return this.getResource("{route["route"]}", {values}, query);',
            "  }", "",
        ]
    lines += ["}", ""]
    return {
        ROOT / "sdks/typescript/src/generated.ts": "\n".join(lines),
        ROOT / "sdks/typescript/LICENSE": (ROOT / "LICENSE").read_text(),
    }
