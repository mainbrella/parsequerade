"""Generate Python's public types, resource methods and bundled runtime contracts."""
import json
import re

from sdk_contracts import ROOT, RESOURCE_NAMES, read_contracts, resource_models, runtime_contracts


def snake(value):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", value).lower()


def py_type(schema):
    if "enum" in schema:
        value = "Literal[" + ", ".join(repr(v) for v in schema["enum"]) + "]"
    elif schema["type"] == "array":
        value = f"str | Sequence[{py_type(schema['items'])}]"
    else:
        value = {"string": "str", "boolean": "bool", "integer": "int"}[schema["type"]]
    return value + (" | None" if schema.get("nullable") else "")


def outputs():
    routes, write = read_contracts()
    lines = [
        '# Generated by scripts/generate_sdks.py. Do not edit.',
        'from __future__ import annotations',
        'from typing import Generic, Literal, Mapping, Sequence, TypeVar, TypedDict, cast',
        'from ._contracts import validate_segment',
        '', 'T = TypeVar("T")',
        'Query = Mapping[str, str | int | bool | Sequence[str]] | Sequence[tuple[str, str | int | bool | Sequence[str]]]',
        '', 'class Page(TypedDict, Generic[T]):', '    items: list[T]', '    nextCursor: str | None', '',
    ]
    names = ['Page', 'Query']
    for name, schema in resource_models(routes):
        names.append(name)
        required = schema["required"]
        lines += [f'class _{name}Required(TypedDict):']
        lines += [f'    {field}: {py_type(value)}' for field, value in schema['properties'].items() if field in required]
        lines += ['', f'class {name}(_{name}Required, total=False):']
        lines += [f'    {field}: {py_type(value)}' for field, value in schema['properties'].items() if field not in required]
        lines += ['']
    lines += ['class AgeRatingUpdate(TypedDict, total=False):']
    lines += [f'    {field}: {py_type(schema)}' for field, schema in write['attributes'].items()]
    names.append('AgeRatingUpdate')
    for route in routes:
        name = route['handler'][0].upper() + route['handler'][1:] + 'Query'
        names.append(name)
        lines += ['', f'class {name}(TypedDict, total=False):']
        lines += [f'    {p["name"]}: {py_type(p["schema"])}' for p in route['parameters']]
    lines += ['', 'class ResourceClient:', '    def get(self, path: str, query: Query | None = None) -> dict:', '        raise NotImplementedError', '']
    for route in routes:
        params = re.findall(r'\{(\w+)\}', route['route'])
        result = RESOURCE_NAMES[route['type']]
        if route['collection']:
            result = f'Page[{result}]'
        query_name = route['handler'][0].upper() + route['handler'][1:] + 'Query'
        args = ''.join(f', {snake(p)}: str' for p in params)
        path = route['route']
        for p in params:
            path = path.replace('{' + p + '}', '{' + snake(p) + '}')
        lines += [f'    def {snake(route["handler"])}(self{args}, query: {query_name} | Query | None = None) -> {result}:',
                  f'        """Read `{route["route"]}` directly from Apple."""']
        # Validate each segment before interpolation so slashes cannot introduce other routes.
        for p in params:
            lines += [f'        validate_segment({snake(p)}, locale={p == "locale"})']
        lines += [f'        return cast({result}, self.get(f"{path}", cast(Query | None, query)))', '']
    lines += ['__all__ = ' + repr(names), '']
    base = ROOT / 'sdks/python'
    return {
        base / 'src/parsequerade/_generated.py': '\n'.join(lines),
        base / 'src/parsequerade/contracts.json': json.dumps(runtime_contracts(), indent=2) + '\n',
        base / 'LICENSE': (ROOT / 'LICENSE').read_text(),
    }
