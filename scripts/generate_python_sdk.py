"""Generate Python's public types, resource methods and bundled runtime contracts."""
import json
import re

from sdk_contracts import (
    CATALOG, ROOT, RESOURCE_NAMES, model_definitions, operation_models,
    read_contracts, resource_models, runtime_contracts,
)


def snake(value):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", value).lower()


def py_type(schema, models, *, response=False, optional=False):
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        target = models[name]
        value = name if target["type"] == "object" or not response else py_type(target, models, response=True)
    elif "enum" in schema and not response:
        value = "Literal[" + ", ".join(repr(v) for v in schema["enum"]) + "]"
    elif schema["type"] == "array":
        item = py_type(schema["items"], models, response=response)
        value = f"list[{item}]" if response else f"str | Sequence[{item}]"
    else:
        value = {"string": "str", "boolean": "bool", "integer": "int", "number": "float"}[schema["type"]]
    # Reads preserve Apple's explicit nulls independently of sparse field absence.
    return value + (" | None" if schema.get("nullable") or response and optional else "")


def lift_nested_models(models):
    """Give inline objects stable names so response types retain their full shape."""
    result = {}

    def visit(name, schema):
        schema = dict(schema)
        if schema.get("type") == "object":
            properties = {}
            for field, value in schema.get("properties", {}).items():
                nested_name = name + field[0].upper() + field[1:]
                if value.get("type") == "object":
                    visit(nested_name, value)
                    value = {**value, "$ref": "#/components/schemas/" + nested_name}
                elif value.get("type") == "array" and value["items"].get("type") == "object":
                    visit(nested_name + "Item", value["items"])
                    value = {**value, "items": {"$ref": "#/components/schemas/" + nested_name + "Item"}}
                properties[field] = value
            schema["properties"] = properties
        result[name] = schema

    for name, schema in models.items():
        visit(name, schema)
    return result


def typed_dict(name, schema, models, *, response=False):
    required = schema.get("required", [])
    required_lines = [
        f'    {field}: {py_type(value, models, response=response)}'
        for field, value in schema["properties"].items() if field in required
    ]
    optional_lines = [
        f'    {field}: {py_type(value, models, response=response, optional=True)}'
        for field, value in schema["properties"].items() if field not in required
    ]
    return [f'class _{name}Required(TypedDict):', *(required_lines or ['    pass']), '',
            f'class {name}(_{name}Required, total=False):', *(optional_lines or ['    pass']), '']


def outputs():
    routes, write = read_contracts("python")
    read_models = lift_nested_models({**model_definitions("python"), **dict(resource_models(routes))})
    operations = operation_models("python")
    models = {**read_models, **operations}
    lines = [
        '# Generated by scripts/generate_sdks.py. Do not edit.',
        'from __future__ import annotations',
        'from typing import Generic, Literal, Mapping, Sequence, TypeVar, TypedDict, cast',
        'from ._validation import validate_segment',
        '', 'T = TypeVar("T")',
        'Query = Mapping[str, str | int | bool | Sequence[str]] | Sequence[tuple[str, str | int | bool | Sequence[str]]]',
        '', 'class Page(TypedDict, Generic[T]):', '    items: list[T]', '    nextCursor: str | None', '',
    ]
    names = ['Page', 'Query']
    for name, schema in read_models.items():
        names.append(name)
        if schema["type"] == "object":
            lines += typed_dict(name, schema, models, response=True)
        else:
            lines += [f'{name} = {py_type(schema, models)}', '']
    lines += ['class AgeRatingUpdate(TypedDict, total=False):']
    lines += [f'    {field}: {py_type(schema, models)}' for field, schema in write['attributes'].items()]
    names.append('AgeRatingUpdate')
    for handler, attributes in CATALOG["metadataUpdates"].items():
        name = handler[0].upper() + handler[1:] + "Update"
        names.append(name)
        lines += ['', f'class {name}(TypedDict, total=False):']
        lines += [f'    {field}: {py_type(schema, models)}' for field, schema in attributes.items()]
    for name, schema in operations.items():
        names.append(name)
        lines += ['']
        if schema["type"] == "object":
            lines += typed_dict(name, schema, models)
        else:
            lines += [f'{name} = {py_type(schema, models)}', '']
    for route in routes:
        name = route['handler'][0].upper() + route['handler'][1:] + 'Query'
        names.append(name)
        lines += ['', f'class {name}(TypedDict, total=False):']
        lines += [f'    {p["name"]}: {py_type(p["schema"], models)}' for p in route['parameters']] or ['    pass']
    lines += ['', 'class ResourceClient:', '    def get(self, path: str, query: Query | None = None) -> dict:', '        raise NotImplementedError', '']
    for route in routes:
        params = re.findall(r'\{(\w+)\}', route['route'])
        result = RESOURCE_NAMES[route['type']]
        if route['collection']:
            result = f'Page[{result}]'
        query_name = route['handler'][0].upper() + route['handler'][1:] + 'Query'
        args = ''.join(f', {snake(p)}: str' for p in params)
        path = route['route']
        for p in params:
            path = path.replace('{' + p + '}', '{' + snake(p) + '}')
        lines += [f'    def {snake(route["handler"])}(self{args}, query: {query_name} | Query | None = None) -> {result}:',
                  f'        """Read `{route["route"]}` directly from Apple."""']
        # Validate each segment before interpolation so slashes cannot introduce other routes.
        for p in params:
            lines += [f'        validate_segment({snake(p)}, locale={p == "locale"})']
        lines += [f'        return cast({result}, self.get(f"{path}", cast(Query | None, query)))', '']
    lines += ['__all__ = ' + repr(names), '']
    base = ROOT / 'sdks/python'
    return {
        base / 'src/parsequerade/_generated.py': '\n'.join(lines),
        base / 'src/parsequerade/contracts.json': json.dumps(runtime_contracts("python"), indent=2) + '\n',
        base / 'LICENSE': (ROOT / 'LICENSE').read_text(),
    }
