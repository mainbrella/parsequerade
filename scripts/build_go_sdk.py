"""Build and stage the shared Rust static library for the Go SDK's current target."""
import argparse
import hashlib
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--target", help="Rust target triple; configure Go and a matching C compiler separately")
    args = parser.parse_args()
    command = ["cargo", "build", "--release", "--locked", "--manifest-path", str(ROOT / "sdks/native/Cargo.toml")]
    if args.target:
        command += ["--target", args.target]
    subprocess.run(command, cwd=ROOT, check=True)
    target_dir = Path(os.environ.get("CARGO_TARGET_DIR", ROOT / "sdks/native/target"))
    if not target_dir.is_absolute():
        target_dir = ROOT / target_dir
    target = args.target or os.environ.get("CARGO_BUILD_TARGET")
    if target:
        target_dir /= target
    source = target_dir / "release/libparsequerade_native.a"
    if not source.exists():
        raise SystemExit("The Go SDK requires a Rust static archive for a cgo-supported target.")
    destination = ROOT / "sdks/go/native"
    destination.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, destination / source.name)
    shutil.copy2(ROOT / "sdks/native/include/parsequerade.h", destination / "parsequerade.h")
    # cgo does not track changes in linked archives. A Go source fingerprint
    # invalidates its build cache when the shared core changes.
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    stamp = ROOT / "sdks/go/native_build.go"
    contents = ("// Code generated by scripts/build_go_sdk.py. DO NOT EDIT.\n"
                "package parsequerade\n\nconst nativeArchiveDigest = \"" + digest + "\"\n")
    if not stamp.exists() or stamp.read_text() != contents:
        stamp.write_text(contents)
    print("Staged Go native library and C header for " + (target or sys.platform))


if __name__ == "__main__":
    main()
